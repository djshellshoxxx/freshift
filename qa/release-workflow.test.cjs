'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const workflow=fs.readFileSync('.github/workflows/release.yml','utf8');
const main=fs.readFileSync('main.go','utf8');
const docs=fs.readFileSync('docs/index.html','utf8');
const web=fs.readFileSync('web/index.html','utf8');
const smoke=fs.readFileSync('qa/api-smoke.py','utf8');
assert.match(main,/const Version = "0\\.4\\.0"/,'Go API version not bumped');
assert.match(docs,/FRESHSIFT v0\\.4\\.0/,'Pages visible version not bumped');
assert.match(web,/FRESHSIFT v0\\.4\\.0/,'Go dashboard visible version not bumped');
assert.match(smoke,/\['version'\]=='0\\.4\\.0'/,'API smoke version mismatch');
assert.match(workflow,/gh release view v0\\.4\\.0/,'release must detect existing immutable tag');
assert.match(workflow,/gh release create v0\\.4\\.0/,'release must create new 0.4.0 tag');
assert.match(workflow,/--target "\$GITHUB_SHA"/,'release must tag current release commit');
assert.match(workflow,/FreshSift-windows-amd64\\.exe/);
assert.match(workflow,/GOOS: windows/);
assert.match(workflow,/go test -race/);
assert.doesNotMatch(workflow,/gh release upload v0\\.3\\.0/,'existing 0.3.0 release must remain untouched');
console.log('PASS: v0.4.0 version consistency and immutable Windows release publishing contract');
